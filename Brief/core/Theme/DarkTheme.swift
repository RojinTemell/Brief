import SwiftUI

struct DarkTheme: AppTheme {

    // MARK: Backgrounds

    let backgroundPrimary = AppColor.backgroundPrimary
    let backgroundSecondary = AppColor.backgroundSecondary

    // MARK: Surfaces

    let surface = AppColor.surface
    let surfaceElevated = AppColor.surfaceElevated

    // MARK: Text

    let textPrimary = AppColor.textPrimary
    let textSecondary = AppColor.textSecondary
    let textTertiary = AppColor.textTertiary
    let textInverse = AppColor.textInverse

    // MARK: Borders

    let borderSubtle = AppColor.borderSubtle
    let borderDefault = AppColor.borderDefault

    // MARK: Accent

    let accentPrimary = AppColor.accentPrimary
    let accentSecondary = AppColor.accentSecondary
}
